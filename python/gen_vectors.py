"""Generate the RTL constant tables and the testbench vectors from the golden model.

    uv run python python/gen_vectors.py

Writes:
  rtl/twiddle_rom.v                     ROM module: ML-KEM zetas (0..127), ML-KEM gammas (128..255),
                                        ML-DSA zetas (256..511), plain integers
  build/vectors/ntt_cases.txt           test cases for tb_ntt_core (shared by every configuration)
  build/vectors/ntt_P{P}_S{S}_trace.txt expected cycle trace per configuration (schedule.py)
  build/vectors/ntt_P{P}_S{S}_mem.txt   expected memory after every case
  build/vectors/keccak_cases.txt        SHA3/SHAKE cases for tb_keccak (expected values from hashlib)
  build/vectors/top_P{P}_S{S}.txt       host transcript for tb_top: requests, gaps, resets, expected responses
"""

import hashlib
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pqc_golden.params import DILITHIUM, KYBER, N  # noqa: E402
from pqc_golden.poly import kyber_gammas  # noqa: E402
from pqc_golden.schedule import run  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OPS = {"NTT": 0, "INTT": 1, "PWM": 2, "MUL": 3}
BUFS = {"A": 0, "B": 1, "C": 2}


def rom_entries() -> list[int]:
    return KYBER.zetas + kyber_gammas() + DILITHIUM.zetas  # 128 + 128 + 256


def write_rom() -> None:
    lines = [
        "// GENERATED by python/gen_vectors.py from python/pqc_golden (do not edit).",
        "// Twiddle ROM, plain integers (no Montgomery factor), synchronous read (1 cycle).",
        "//   0..127   ML-KEM zetas[k]  = 17^bitrev7(k) mod 3329          (FIPS 203 Appendix A)",
        "//   128..255 ML-KEM gamma[i]  = 17^(2*bitrev7(i)+1) mod 3329    (FIPS 203 Appendix A)",
        "//   256..511 ML-DSA zetas[k]  = 1753^bitrev8(k) mod 8380417     (FIPS 204 Appendix B)",
        "// Entry 0 of each zeta table is never read (127 and 255 entries used).",
        "module twiddle_rom (",
        "    input  wire        clk,",
        "    input  wire [8:0]  addr,",
        "    output reg  [22:0] data",
        ");",
        "    always @(posedge clk) begin",
        "        case (addr)",
    ]
    for a, v in enumerate(rom_entries()):
        lines.append(f"            9'd{a}: data <= 23'd{v};")
    lines += ["            default: data <= 23'd0;", "        endcase", "    end", "endmodule", ""]
    path, text = ROOT / "rtl" / "twiddle_rom.v", "\n".join(lines)
    if not path.exists() or path.read_text(encoding="utf8") != text:  # don't touch it while a build reads it
        path.write_text(text, encoding="utf8")


def ntt_cases() -> list[tuple[str, str, str, dict[str, list[int]]]]:
    """(scheme, op, buf, initial memory) for tb_ntt_core: every operation, both schemes, edge + random data."""
    rng = random.Random(2026)
    cases = []
    for s in (KYBER, DILITHIUM):
        q = s.q
        rnd = lambda: [rng.randrange(q) for _ in range(N)]  # noqa: E731
        edge = [q - 1 if i % 3 == 0 else (1 if i % 3 == 1 else 0) for i in range(N)]
        for op, buf in [("NTT", "A"), ("NTT", "B"), ("NTT", "C"), ("INTT", "A"), ("INTT", "C"), ("PWM", "A"), ("MUL", "A")]:
            cases.append((s.name, op, buf, {"A": rnd(), "B": rnd(), "C": rnd()}))
        cases.append((s.name, "MUL", "A", {"A": edge, "B": [q - 1] * N, "C": [0] * N}))
        cases.append((s.name, "MUL", "A", {"A": [0] * N, "B": rnd(), "C": rnd()}))
        one = [1] + [0] * (N - 1)
        x255 = [0] * (N - 1) + [1]
        alt = [q - 1 if i % 2 else 0 for i in range(N)]
        cases.append((s.name, "MUL", "A", {"A": one, "B": x255, "C": rnd()}))  # 1 * x^255
        cases.append((s.name, "NTT", "B", {"A": rnd(), "B": alt, "C": rnd()}))  # alternating 0, q-1
    # last case: tb_ntt_core first resets the core in the middle of this MUL, then runs it normally
    cases.append(("ML-DSA", "MUL", "A", {"A": rnd(), "B": rnd(), "C": rnd()}))
    return cases


def write_ntt_vectors() -> None:
    out = ROOT / "build" / "vectors"
    out.mkdir(parents=True, exist_ok=True)
    cases = ntt_cases()
    scheme = {"ML-KEM": KYBER, "ML-DSA": DILITHIUM}
    with open(out / "ntt_cases.txt", "w") as f:
        f.write(f"{len(cases)}\n")
        for sname, op, buf, mem in cases:
            f.write(f"{1 if sname == 'ML-DSA' else 0} {OPS[op]} {BUFS[buf]}\n")
            for b in "ABC":
                f.write(" ".join(map(str, mem[b])) + "\n")
    for P in (1, 2, 4):
        for special in (0, 1):
            trace, mems = [], []
            for n, (sname, op, buf, mem) in enumerate(cases):
                m = {k: list(v) for k, v in mem.items()}
                tr = run(op, scheme[sname], P, m, buf, dil_special=bool(special))
                trace += [f"{n} {ln}" for ln in tr.lines()]
                mems.append(" ".join(str(x) for b in "ABC" for x in m[b]))
            (out / f"ntt_P{P}_S{special}_trace.txt").write_text("\n".join(trace) + "\n")
            (out / f"ntt_P{P}_S{special}_mem.txt").write_text("\n".join(mems) + "\n")


HASH_MODES = [("sha3_256", 136), ("sha3_512", 72), ("shake_128", 168), ("shake_256", 136)]


def hash_ref(mode: int, msg: bytes, outlen: int) -> bytes:
    name = HASH_MODES[mode][0]
    h = hashlib.new(name, msg)
    return h.digest(outlen) if name.startswith("shake") else h.digest()


def keccak_cases() -> list[tuple[int, bytes, int]]:
    """Each mode around its own rate: empty, 1, r-1, r, r+1, 2r, 2r+1, multi-block; SHAKE outputs across
    squeeze-block boundaries (r-1, r, r+1, 2r+5)."""
    rng = random.Random(202)
    cases = [(0, b"abc", 32), (1, b"abc", 64)]
    for mode, (name, r) in enumerate(HASH_MODES):
        for n in sorted({0, 1, r - 1, r, r + 1, 2 * r, 2 * r + 1, 3 * r + 7}):
            msg = bytes(rng.randrange(256) for _ in range(n))
            outs = [32 if mode == 0 else 64] if mode < 2 else [1, 32, r - 1, r, r + 1, 2 * r + 5]
            for o in outs if (mode < 2 or n in (0, r)) else outs[1:2]:  # SHA3: its one length, always
                cases.append((mode, msg, o))
    return cases


def write_keccak_vectors() -> None:
    out = ROOT / "build" / "vectors"
    out.mkdir(parents=True, exist_ok=True)
    cases = keccak_cases()
    with open(out / "keccak_cases.txt", "w") as f:
        f.write(f"{len(cases)}\n")
        for mode, msg, o in cases:
            f.write(f"{mode} {len(msg)} {o}\n")
            f.write(" ".join(map(str, msg)) + "\n")
            f.write(" ".join(map(str, hash_ref(mode, msg, o))) + "\n")


def top_transcript(P: int, special: int, timeout_gap: int) -> list[tuple]:
    """Requests and the exact responses the system must give: ("S", bytes), ("E", bytes), ("G", cycles), ("R",)."""
    from host import protocol as pr
    from pqc_golden.ntt import ntt
    from pqc_golden.poly import multiply

    rng = random.Random(1500 + P)
    scheme = {pr.KYBER_ID: KYBER, pr.DILITHIUM_ID: DILITHIUM}
    t: list[tuple] = []

    def xact(req: bytes, rsp: bytes) -> None:
        t.append(("S", req))
        t.append(("E", rsp))

    def cycles(op: str, s, buf: str = "A") -> bytes:
        mem = {b: [0] * N for b in "ABC"}
        return run(op, s, P, mem, buf).total.to_bytes(4, "little")

    xact(bytes([0x00, 0x13, 0x37]) + pr.frame(pr.PING), pr.response(pr.OK, bytes([0x50, 0x51, P, special])))  # garbage first
    for sid in (pr.KYBER_ID, pr.DILITHIUM_ID):
        s = scheme[sid]
        f = [rng.randrange(s.q) for _ in range(N)]
        g = [rng.randrange(s.q) for _ in range(N)]
        xact(pr.load(sid, 0, f), pr.response(pr.OK))
        xact(pr.load(sid, 1, g), pr.response(pr.OK))
        xact(pr.run(sid, pr.OP["MUL"]), pr.response(pr.OK, cycles("MUL", s)))
        xact(pr.read(2), pr.response(pr.OK, pr.pack_poly(multiply(f, g, s))))
        xact(pr.read(0), pr.response(pr.OK, pr.pack_poly(ntt(f, s))))
        # standalone NTT then INTT on B gives g back... B holds NTT(g) after MUL: INTT(B) = g
        xact(pr.run(sid, pr.OP["INTT"], 1), pr.response(pr.OK, cycles("INTT", s, "B")))
        xact(pr.read(1), pr.response(pr.OK, pr.pack_poly(g)))
        a_now = ntt(f, s)
        # atomic LOAD: a bad coefficient at the start, middle or end changes nothing
        for pos in (0, 128, 255):
            bad = list(f)
            bad[pos] = s.q  # first out-of-range value
            xact(pr.load(sid, 0, bad), pr.response(pr.ERR_RANGE))
        bad = list(f)
        bad[7] = (1 << 24) - 1
        xact(pr.load(sid, 0, bad), pr.response(pr.ERR_RANGE))
        xact(pr.load(sid, 0, f, bad_checksum=True), pr.response(pr.ERR_CHK))
        xact(pr.read(0), pr.response(pr.OK, pr.pack_poly(a_now)))
        # interrupted transfer: half a LOAD, then silence longer than the timeout
        req = pr.load(sid, 0, g)
        t.append(("S", req[: len(req) // 2]))
        t.append(("G", timeout_gap))
        t.append(("E", pr.response(pr.ERR_TIMEOUT)))
        xact(pr.read(0), pr.response(pr.OK, pr.pack_poly(a_now)))
    # argument, length, command and state errors
    xact(pr.frame(0x77), pr.response(pr.ERR_CMD))
    xact(pr.frame(pr.READ, bytes([0, 0])), pr.response(pr.ERR_LEN))
    xact(pr.frame(pr.READ, bytes([3])), pr.response(pr.ERR_ARG))
    xact(pr.frame(pr.RUN, bytes([0, 4, 0])), pr.response(pr.ERR_ARG))
    xact(pr.frame(pr.LOAD, bytes([2, 0]) + bytes(768)), pr.response(pr.ERR_ARG))
    xact(pr.run(pr.KYBER_ID, pr.OP["NTT"], 0), pr.response(pr.ERR_STATE))  # A was loaded as ML-DSA
    xact(pr.run(pr.KYBER_ID, pr.OP["MUL"]), pr.response(pr.ERR_STATE))
    # hashing, including rate boundaries and an output longer than one squeeze block
    for mode, msg, outlen in [(0, b"abc", 32), (1, b"", 64), (2, bytes(range(168)), 200), (3, bytes(137), 33)]:
        xact(pr.hash_req(mode, msg, outlen), pr.response(pr.OK, hash_ref(mode, msg, outlen)))
    xact(pr.hash_req(0, b"abc", 31), pr.response(pr.ERR_ARG))
    xact(pr.hash_req(2, b"abc", 0), pr.response(pr.ERR_ARG))
    # reset in the middle of a request, then normal operation; tags are cleared by reset
    t.append(("S", pr.frame(pr.PING)[:2]))
    t.append(("G", 400))  # let the second byte finish on the wire: the controller is now mid-header
    t.append(("R",))
    xact(pr.frame(pr.PING), pr.response(pr.OK, bytes([0x50, 0x51, P, special])))
    xact(pr.run(pr.DILITHIUM_ID, pr.OP["NTT"], 0), pr.response(pr.ERR_STATE))
    return t


def write_top_vectors(timeout_gap: int = 3000) -> None:
    out = ROOT / "build" / "vectors"
    for P in (1, 2, 4):
        for special in (0, 1):
            with open(out / f"top_P{P}_S{special}.txt", "w") as f:
                for item in top_transcript(P, special, timeout_gap):
                    if item[0] in ("S", "E"):
                        f.write(f"{item[0]} {len(item[1])} " + " ".join(map(str, item[1])) + "\n")
                    elif item[0] == "G":
                        f.write(f"G {item[1]}\n")
                    else:
                        f.write("R 0\n")
                f.write("X 0\n")


def main() -> None:
    write_rom()
    write_ntt_vectors()
    write_keccak_vectors()
    write_top_vectors()


if __name__ == "__main__":
    main()
